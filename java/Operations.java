class Operations {
  public static void main(String[] args) {
    int x = 5;

    System.out.println("x: " + x);

    x = x + 5;

    System.out.println("x + 5: " + x);

    x = x - 5;

    System.out.println("x - 5: " + x);

    x = x * 5;

    System.out.println("x * 5: " + x);

    x = x / 5;

    System.out.println("x / 5: " + x);
  }
}
